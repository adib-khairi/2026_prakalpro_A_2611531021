nilai_1021 = int(input("Input nilai angka: "))

if nilai_1021 >= 81:
    print("A")
elif nilai_1021 >= 70:
    print("B")
elif nilai_1021 >= 60:
    print("C")
elif nilai_1021 >= 50:
    print("D")
else:
    print("E")